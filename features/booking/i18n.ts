export function normalizeBookingLocale(language?: string | null): BookingLocale {
  const normalized = (language ?? "").trim().replace("_", "-").toLowerCase();

  if (normalized.startsWith("ko")) return "ko";
  if (normalized.startsWith("ja")) return "ja";
  if (normalized === "zh-cn" || normalized === "zh-sg") return "zh-CN";
  if (normalized === "zh-tw") return "zh-TW";
  if (normalized === "zh-hk" || normalized === "zh-mo") return "zh-HK";
  if (normalized.startsWith("zh")) return "zh-CN";
  if (normalized.startsWith("vi")) return "vi";
  if (normalized.startsWith("th")) return "th";
  return "en";
}

export function isBookingLocale(value: string | null): value is BookingLocale {
  return BOOKING_LOCALES.includes(value as BookingLocale);
}

export function t(
  locale: BookingLocale,
  key: BookingTranslationKey,
  variables?: Record<string, string | number>
) {
  const template = translations[locale]?.[key] ?? translations.ko[key] ?? translations.en[key];

  return Object.entries(variables ?? {}).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template
  );
}
